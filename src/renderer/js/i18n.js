  function setLang(l) {
    lang = DICT[l] ? l : 'uk';
    document.documentElement.lang = lang;
  }

  function t(key, params) {
    let s = (DICT[lang] && DICT[lang][key]) ?? DICT.uk[key] ?? key;
    if (typeof s !== 'string') return key;
    if (params) for (const [k, v] of Object.entries(params)) s = s.split('{' + k + '}').join(String(v));
    return s;
  }

  function tp(key, n) {
    const forms = (DICT[lang] && DICT[lang][key]) || DICT.uk[key];
    if (!forms || typeof forms !== 'object') return String(n);
    let cat = 'other';
    try {
      cat = new Intl.PluralRules(lang).select(n);
    } catch {
      cat = n === 1 ? 'one' : 'other';
    }
    return (forms[cat] || forms.other || forms.many || '').split('{n}').join(String(n));
  }

  function relative(ts) {
    if (!ts) return t('longAgo');
    const diff = Date.now() - ts;
    if (diff < 60 * 1000) return t('justNow');
    const rtf = new Intl.RelativeTimeFormat(lang, { numeric: 'auto', style: 'short' });
    if (diff < 3600 * 1000) return rtf.format(-Math.round(diff / 60000), 'minute');
    if (diff < 24 * 3600 * 1000) return rtf.format(-Math.round(diff / 3600000), 'hour');
    if (diff < 7 * 24 * 3600 * 1000) return rtf.format(-Math.round(diff / 86400000), 'day');
    return new Date(ts).toLocaleDateString(lang);
  }

